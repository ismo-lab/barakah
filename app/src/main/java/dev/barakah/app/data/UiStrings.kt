    fun of(text: String): String {
        if (language == "en" || text.isEmpty()) return text
        return translations[language]?.get(text) ?: text
    }

    /** Fills a translated template. Unknown placeholders fall back to the English template. */
    fun format(key: String, vararg args: Any?): String {
        val template = translations[language]?.get(key) ?: key
        return try {
            String.format(Locale.ROOT, template, *args)
        } catch (e: Exception) {
            key
        }
    }
