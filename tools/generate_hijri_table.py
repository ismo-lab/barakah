"""Regenerate UmmAlQuraTable.kt from the MIT-licensed umalqura/umalqura month table."""
import datetime
import re
import sys
import urllib.request

URL = 'https://raw.githubusercontent.com/umalqura/umalqura/master/src/UmAlQuraStatic.ts'
OUT = 'app/src/main/java/dev/barakah/app/util/UmmAlQuraTable.kt'
EPOCH = datetime.date(1970, 1, 1)

source = sys.argv[1] if len(sys.argv) > 1 else URL
if source.startswith('http'):
    request = urllib.request.Request(source, headers={'User-Agent': 'barakah-hijri-table/1.0'})
    text = urllib.request.urlopen(request, timeout=60).read().decode('utf-8')
else:
    text = open(source, encoding='utf-8').read()

rows = [
    (int(m.group(1)), int(m.group(2), 16), datetime.date(int(m.group(3)), int(m.group(4)), int(m.group(5))))
    for m in re.finditer(r'(\d{4})\*/\s*(0x[0-9A-Fa-f]+),\s*(\d{4}),\s*(\d+),\s*(\d+)', text)
]
assert len(rows) == 183 and rows[0][0] == 1318 and rows[-1][0] == 1500, len(rows)

starts = []
for _, flags, gregorian in rows:
    day = (gregorian - EPOCH).days
    for month in range(1, 13):
        starts.append(day)
        day += 29 + ((flags >> (month - 1)) & 1)
assert len(starts) == 2196 and all(a < b for a, b in zip(starts, starts[1:]))
end = (rows[-1][2] - EPOCH).days + sum(29 + ((rows[-1][1] >> m) & 1) for m in range(12))

lines = ['    ' + ', '.join(str(v) for v in starts[i:i + 12]) + ',' for i in range(0, len(starts), 12)]
out = '''package dev.barakah.app.util

/**
 * Umm al-Qura month starts, as days since 1970-01-01, from Hijri 1318-01-01 to 1500-12-01.
 * Generated from the MIT-licensed table in https://github.com/umalqura/umalqura (see
 * docs/UMMALQURA_DATA_LICENSE.txt). Bundled here so every device gets the same dates; no device
 * conversion uses no device calendar data or API level. Generated by tools/generate_hijri_table.py.
 */
internal object UmmAlQuraTable {
    const val FIRST_YEAR = 1318
    const val MONTHS = 2196
    /** 1501-01-01: first day after the table. */
    const val END_EPOCH_DAY = %d

    @JvmField
    val monthStartEpochDays = intArrayOf(
%s
    )
}
''' % (end, '\n'.join(lines))
open(OUT, 'w', encoding='utf-8', newline='\n').write(out)
print(f'wrote {OUT}: {len(starts)} month starts')
